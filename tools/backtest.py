"""Local validation harness for the gta6-trophy-rarity-forecast-01 entry.

Replicates the scoring rule from competition.yaml (pinball loss on the
logit scale) and checks the entry against:

  * practice-proxy truths -- the practice cases p00/p01 straddle Exophase's
    first refresh (638 -> 3,868 players tracked, 943 -> 4,276 trophies
    earned, every rate but the 100% one falling). The server-side answers
    are not published, so four truth variants are built that are all
    consistent with those public aggregates, differing only in how the
    103 residual new earners (beyond the 3,230 who all hold the 100%
    trophy) spread over the other trophies;
  * synthetic final worlds -- f00-shaped cases whose histories are
    generated by a cohort model (new player cohorts join at each refresh
    and adopt trophies along a per-family curve), scored against the
    simulated rates at the target, over 10 seeded worlds per family
    (Weibull, log-logistic, delayed-sigmoid);
  * edge cases, determinism and runtime.

Everything runs in-process (the entry is imported and its forecast_case
called directly); nothing is written to disk. The entry's own main()
file-writing path is the same three lines as the kit starter's and is
exercised by the grader's sandbox, not here.

Usage: python3 tools/backtest.py   (run from the repository root)
"""

import json
import math
import os
